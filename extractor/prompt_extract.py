_AXIS_HINT_EMPTY = "本问题下暂无已登记的争议对象，请自行命名。"
_AXIS_HINT_TPL = """本问题下已经登记过这些争议对象。如果当前观点裁决的是同一件事，
  **必须逐字复用**下面的说法，不要改写措辞（跨回答比对靠它对齐）；
  确实是新的对象才另起一个：
  {axes}"""


def _axis_hint(known_axes) -> str:
    items = [str(a).strip() for a in (known_axes or []) if str(a or "").strip()]
    if not items:
        return _AXIS_HINT_EMPTY
    seen, uniq = set(), []
    for item in items:
        if item not in seen:
            seen.add(item)
            uniq.append(item)
    return _AXIS_HINT_TPL.format(axes="；".join(f"「{a}」" for a in uniq[:12]))


USER_PROMPT_TEMPLATE = """【原问题】
{question}

【回答作者】
{author}

【回答正文】
{content}

【任务】
按系统规则生成这篇回答的完整观点树。

输出前逐项自检：
1. 只有一个 root，且忠实回应原问题；
2. 从 root 沿 branch 能理解到所有 collision，所有可见叶子都是 collision 且无 children；
2b. **没有任何 branch 只含 1 个子节点**；已达到密度带的观点直接挂在 root 下，不套多余的 branch；
3. 每个 collision 通过 D1～D4：恰好 1 个争议轴、2～3 个语义槽位、40～75 字、1～2 条支撑；
4. 全部 collision 通过 D5：字数极差 ≤30，最长 ≤最短的 2 倍；
5. 每个 collision 都填了 axis / stance / conditions；axis 是可判定的对象而非话题；
6. stance 忠于原文：只描述现象而不主张该怎么做的，必须是 descriptive；
7. excludes 只在原文真有排除表述时填写，没有就留空数组；
8. 每个 statement 是作者视角的一句话，无标题前缀，句中无句号分号序号；
9. 每个 collision 至少一条逐字可定位的 support.quote；
10. root、branch 和 collision 都有 12～26 字、可独立成立的 display_text，保留对象和判断方向，无目录词、无长句节选、无省略号；
11. 每个 collision 都有 60～140 字的 explanation，讲的是成立前提、为什么这么看、边界在哪，**不是 statement 的改写或复读**；
12. 例子、经历、事实、操作步骤在 support 里，信息边界在 boundaries 里。

只输出 JSON。"""


def build_messages(question: str, content: str, author: str = "匿名用户",
                   known_axes=None):
    """构造抽取消息。known_axes 是同一问题下已登记的 axis 清单，用于跨回答对齐。"""
    return [
        {"role": "system", "content": SYSTEM_PROMPT.replace("{axis_hint}", _axis_hint(known_axes))},
        {
            "role": "user",
            "content": USER_PROMPT_TEMPLATE.format(
                question=question.strip(),
                author=author.strip() or "匿名用户",
                content=content.strip(),
            ),
        },
    ]


